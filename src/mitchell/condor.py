"""Generate an HTCondor DAG that builds a catalogue store in parallel.

Converting a catalogue event by event is slow, mostly because the events are
downloaded and converted one after another.  The events are independent, so
this writes a DAG with one node per event, each building a small single-event
store (``parts/<event>.zarr``), and a final node that merges the parts into the
catalogue with ``mitchell combine``::

    convert_GW150914_095045 ┐
    convert_GW151012_095443 ├─▶ combine ─▶ catalogue.zarr
    ...                     ┘

One store per event avoids concurrent jobs rewriting the same root index, and
lets DAGMan retry a failed event on its own.  Only generation lives here;
``mitchell condor-dag`` is the command-line front end.
"""

from __future__ import annotations

import re
import shlex
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

from mitchell import __version__

Source = Literal["gwtc", "h5"]

#: DAG nodes are named ``convert_<event>``, with anything awkward replaced.
_UNSAFE = re.compile(r"[^A-Za-z0-9_-]")
#: Characters that cannot be carried safely through a DAG VARS value or a
#: comma-separated ``transfer_input_files`` entry.
_FORBIDDEN_IN_PATHS = re.compile(r'["\\,\n]')

#: Measured converting the GWTC-2.1 GW150914 file (134 MB in, 128 MB out): about
#: 270 MB peak memory and 13 s.  These requests leave generous headroom for
#: larger events.
DEFAULT_MEMORY = "2GB"
DEFAULT_DISK = "3GB"
DEFAULT_RETRIES = 3
#: Concurrent downloads when fetching from Zenodo, to be polite to it.
DEFAULT_MAX_DOWNLOADS = 8


@dataclass(frozen=True)
class Node:
    """One event to convert."""

    event: str
    #: The PESummary file, for ``h5`` sources; unused for ``gwtc``.
    h5_path: Path | None = None

    @property
    def name(self) -> str:
        return "convert_" + _UNSAFE.sub("_", self.event)

    @property
    def part(self) -> str:
        return f"parts/{_UNSAFE.sub('_', self.event)}.zarr"


@dataclass(frozen=True)
class Options:
    """Everything that shapes the generated files besides the node list."""

    catalogue: Path
    mitchell: str
    source: Source
    retries: int = DEFAULT_RETRIES
    request_memory: str = DEFAULT_MEMORY
    request_disk: str = DEFAULT_DISK
    max_jobs: int | None = None
    accounting_group: str | None = None
    accounting_group_user: str | None = None
    container_image: str | None = None
    keep_parts: bool = False


def _check_path(path: Path | str, what: str) -> str:
    text = str(path)
    if _FORBIDDEN_IN_PATHS.search(text):
        raise ValueError(
            f"{what} {text!r} contains a quote, backslash, comma or newline, "
            "which cannot be passed through a Condor DAG; rename it."
        )
    return text


def quote_arguments(args: list[str]) -> str:
    """Format *args* as an HTCondor ``arguments`` value (the new syntax).

    The whole value is double-quoted; an argument with whitespace or a quote is
    wrapped in single quotes, and quotes inside are doubled.
    """

    def one(arg: str) -> str:
        if not arg or re.search(r"""[\s'"]""", arg):
            return "'" + arg.replace("'", "''").replace('"', '""') + "'"
        return arg

    return '"' + " ".join(one(a) for a in args) + '"'


def node_names(nodes: list[Node]) -> list[str]:
    """DAG node names, checked for uniqueness (sanitising can collide)."""
    names = [n.name for n in nodes]
    clashes = sorted({n for n in names if names.count(n) > 1})
    if clashes:
        raise ValueError(f"Events map to the same DAG node name: {clashes}")
    return names


def wrapper_script(mitchell: str) -> str:
    """The job executable: a shell wrapper around the ``mitchell`` command."""
    return f"""#!/bin/bash
# Generated by `mitchell condor-dag` (mitchell {__version__}).
#
# gwresults caches each download under the user cache directory, and a worker's
# home directory is often missing or read-only, so point the cache at the job's
# scratch directory (which Condor deletes afterwards).
set -euo pipefail
export XDG_CACHE_HOME="${{_CONDOR_SCRATCH_DIR:-$PWD}}/xdg-cache"
export PYTHONUNBUFFERED=1
# Condor puts a job on hold, instead of failing it, when a file listed in
# transfer_output_files is missing, and a held job stalls the DAG.  If mitchell
# cannot even start (not visible on this worker, say) nothing creates the
# output, so make sure it exists: the job then fails, and DAGMan retries it.
if [ -n "${{MITCHELL_ENSURE_DIR:-}}" ]; then mkdir -p "$MITCHELL_ENSURE_DIR"; fi
exec {shlex.quote(mitchell)} "$@"
"""


def _common_lines(options: Options) -> list[str]:
    lines = [
        "output = logs/$(JOB).out",
        "error  = logs/$(JOB).err",
        "log    = logs/mitchell.log",
    ]
    if options.accounting_group:
        lines.append(f"accounting_group = {options.accounting_group}")
    if options.accounting_group_user:
        lines.append(f"accounting_group_user = {options.accounting_group_user}")
    return lines


def convert_submit(options: Options) -> str:
    """The submit description shared by every ``convert_*`` node."""
    if options.source == "gwtc":
        arguments = ["from-gwtc", "part.zarr", "--event", "$(event)"]
        transfer_in: list[str] = []
    else:
        arguments = [
            "from-pesummary",
            "$(h5file)",
            "part.zarr",
            "--event-name",
            "$(event)",
        ]
        transfer_in = ["transfer_input_files = $(h5)"]

    lines = [
        f"# Generated by `mitchell condor-dag` (mitchell {__version__}).",
        "# One node = one event, built into its own store and sent back to parts/.",
        "executable = run_mitchell.sh",
        f"arguments  = {quote_arguments(arguments)}",
    ]
    if options.container_image:
        lines += [
            "universe = container",
            f"container_image = {options.container_image}",
        ]
    lines += [
        'environment = "MITCHELL_ENSURE_DIR=part.zarr"',
        "should_transfer_files   = YES",
        "when_to_transfer_output = ON_EXIT",
        *transfer_in,
        "transfer_output_files   = part.zarr",
        'transfer_output_remaps  = "part.zarr = $(part)"',
        "request_cpus   = 1",
        f"request_memory = {options.request_memory}",
        f"request_disk   = {options.request_disk}",
        *_common_lines(options),
        "queue",
    ]
    return "\n".join(lines) + "\n"


def combine_submit(options: Options) -> str:
    """The submit description of the final merge node.

    It runs in the local universe, on the submit host, because it only moves
    files within the shared directory the parts were returned to.
    """
    arguments = ["combine", str(options.catalogue), "--parts-dir", "parts"]
    arguments.append("--copy" if options.keep_parts else "--move")
    lines = [
        f"# Generated by `mitchell condor-dag` (mitchell {__version__}).",
        "# Merges parts/*.zarr into the catalogue; runs on the submit host.",
        "universe   = local",
        "executable = run_mitchell.sh",
        f"arguments  = {quote_arguments(arguments)}",
        *_common_lines(options),
        "queue",
    ]
    return "\n".join(lines) + "\n"


def dag_text(nodes: list[Node], options: Options, submit_file: str) -> str:
    """The ``.dag`` file."""
    names = node_names(nodes)
    lines = [
        f"# Generated by `mitchell condor-dag` (mitchell {__version__}).",
        f"# {len(nodes)} event(s) from {options.source} -> {options.catalogue}",
        "# Submit with: condor_submit_dag <this file>.  If it fails part-way, "
        "submit it again:",
        "# DAGMan resumes from the rescue DAG and only reruns what did not finish.",
        "",
        "NODE_STATUS_FILE catalogue.dag.status 30",
        "",
    ]
    max_jobs = options.max_jobs
    if max_jobs is None and options.source == "gwtc":
        max_jobs = DEFAULT_MAX_DOWNLOADS
    for node, name in zip(nodes, names, strict=True):
        lines.append(f"JOB {name} {submit_file}")
        vars_ = [f'event="{_check_path(node.event, "Event name")}"']
        vars_.append(f'part="{node.part}"')
        if node.h5_path is not None:
            h5 = _check_path(node.h5_path.resolve(), "File")
            vars_ += [
                f'h5="{h5}"',
                f'h5file="{_check_path(node.h5_path.name, "File")}"',
            ]
        lines.append(f"VARS {name} " + " ".join(vars_))
        lines.append(f"RETRY {name} {options.retries}")
        lines.append(f"CATEGORY {name} convert")
        # Each attempt returns its store to the same place; a failed attempt may
        # have left a partial one, so clear it before every (re)try.
        lines.append(f"SCRIPT PRE {name} /bin/rm -rf {node.part}")
    if max_jobs is not None:
        lines += ["", f"MAXJOBS convert {max_jobs}"]
    lines += [
        "",
        "JOB combine combine.sub",
        f"RETRY combine {options.retries}",
        f"PARENT {' '.join(names)} CHILD combine",
    ]
    return "\n".join(lines) + "\n"


def write_dag(directory: Path, nodes: list[Node], options: Options) -> Path:
    """Write the DAG, submit files and wrapper script into *directory*.

    Returns the path of the ``.dag`` file.  ``parts/`` and ``logs/`` are
    created because Condor will not create the directories it writes into.
    """
    if not nodes:
        raise ValueError("There are no events to convert.")
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "parts").mkdir(exist_ok=True)
    (directory / "logs").mkdir(exist_ok=True)

    script = directory / "run_mitchell.sh"
    script.write_text(wrapper_script(options.mitchell))
    script.chmod(0o755)

    submit = f"convert_{options.source}.sub"
    (directory / submit).write_text(convert_submit(options))
    (directory / "combine.sub").write_text(combine_submit(options))
    dag = directory / "catalogue.dag"
    dag.write_text(dag_text(nodes, options, submit))
    return dag
